    static let patterns: [(String, NSRegularExpression, Int)] = catalog.keys.filter { $0.contains("{0}") }.sorted { $0.count > $1.count }.compactMap { key in
        let regex = try! NSRegularExpression(pattern: #"\{\d+\}"#)
        let ns = key as NSString
        let matches = regex.matches(in: key, range: NSRange(location: 0, length: ns.length))
        var pattern = "^", start = 0
        for match in matches {
            pattern += NSRegularExpression.escapedPattern(for: ns.substring(with: NSRange(location: start, length: match.range.location - start))) + "([\\s\\S]*?)"
            start = NSMaxRange(match.range)
        }
        pattern += NSRegularExpression.escapedPattern(for: ns.substring(from: start)) + "$"
        guard let compiled = try? NSRegularExpression(pattern: pattern) else { return nil }
        return (key, compiled, matches.count)
    }
    static func text(_ source: String, language: AppLanguage, depth: Int = 0) -> String {
        guard language != .zh, depth < 4 else { return source }
        if let pair = catalog[source] { return language == .en ? pair.0 : pair.1 }
        for (key, regex, count) in patterns {
            guard let match = regex.firstMatch(in: source, range: NSRange(source.startIndex..., in: source)), let pair = catalog[key] else { continue }
            var result = language == .en ? pair.0 : pair.1
            // Replace from high indexes to prevent placeholders inside captured content from being reinterpreted.
            for i in (0..<count).reversed() {
                if let range = Range(match.range(at: i + 1), in: source) {
                    result = result.replacingOccurrences(of: "{\(i)}", with: text(String(source[range]), language: language, depth: depth + 1))
                }
            }
            return result
        }
        for (key, pair) in catalog where key.hasSuffix("：") && source.hasPrefix(key) {
            return (language == .en ? pair.0 : pair.1) + text(String(source.dropFirst(key.count)), language: language, depth: depth + 1)
        }
        for (key, pair) in catalog where key.hasPrefix(" · ") && source.hasSuffix(key) {
            return String(source.dropLast(key.count)) + (language == .en ? pair.0 : pair.1)
        }
        return source
    }
