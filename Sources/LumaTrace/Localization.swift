func tr(_ source: String, language: AppLanguage = Localization.language) -> String { Localization.text(source, language: language) }
func localizedDate(_ date: Date, time: Bool = false) -> String {
    let formatter = DateFormatter(); formatter.locale = Localization.language.locale; formatter.dateStyle = .medium; formatter.timeStyle = time ? .short : .none
    return formatter.string(from: date)
}
