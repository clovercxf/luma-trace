enum AppLanguage: String, CaseIterable, Codable, Identifiable, Sendable {
    case zh = "zh-Hans", en = "en", es = "es"
    var id: String { rawValue }
    var displayName: String { switch self { case .zh: return "简体中文"; case .en: return "English"; case .es: return "Español" } }
    var locale: Locale { regionalLocale(region: Locale.current.region?.identifier) }
    func regionalLocale(region: String?) -> Locale {
        Locale(identifier: rawValue + (region.map { "_" + $0 } ?? ""))
    }
    static var systemDefault: AppLanguage {
        let language = Locale.preferredLanguages.first ?? "en"
        if language.hasPrefix("zh") { return .zh }
        if language.hasPrefix("es") { return .es }
        return .en
    }
}
